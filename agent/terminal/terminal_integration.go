package terminal

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/justindeelux/gotham/agent/docker"
)

const terminalZshEnvScript = `# Gotham terminal integration (generated by the node agent; do not edit).
# Additive and optional: the operator's own ~/.zshenv is sourced first and wins.
# This file only restores ZDOTDIR for the next startup file; it never reads
# stdin and is safe to source twice.

if [ -n "${GOTHAM_TERMINAL_ORIGINAL_ZDOTDIR-}" ]; then
  export ZDOTDIR="$GOTHAM_TERMINAL_ORIGINAL_ZDOTDIR"
  if [ -r "$ZDOTDIR/.zshenv" ]; then
    . "$ZDOTDIR/.zshenv"
  fi
else
  unset ZDOTDIR
  if [ -n "${HOME-}" ] && [ -r "$HOME/.zshenv" ]; then
    . "$HOME/.zshenv"
  fi
fi
# The operator's .zshenv may have set or changed ZDOTDIR, or unset it. Record
# what a plain zsh would keep so the .zshrc can restore it afterwards.
if [ -n "${ZDOTDIR-}" ]; then
  export GOTHAM_TERMINAL_USER_ZDOTDIR="$ZDOTDIR"
  export GOTHAM_TERMINAL_HAS_ZDOTDIR=1
else
  unset GOTHAM_TERMINAL_USER_ZDOTDIR
  unset GOTHAM_TERMINAL_HAS_ZDOTDIR
fi
if [ -n "${GOTHAM_TERMINAL_ZDOTDIR-}" ]; then
  export ZDOTDIR="$GOTHAM_TERMINAL_ZDOTDIR"
fi
unset GOTHAM_TERMINAL_ORIGINAL_ZDOTDIR
`

const terminalZshRcScript = `# Gotham terminal integration (generated by the node agent; do not edit).
# Additive and optional: the operator's ~/.zshrc is sourced first and wins.
# This file only adds OSC 133 prompt marks. It never reads stdin and is safe to
# source twice.

if [[ ${__gotham_integration_loaded-} == 1 ]]; then
  return 0
fi
__gotham_integration_loaded=1

# Source the operator's .zshrc with ZDOTDIR exactly as a plain zsh would have
# it: their custom value, or unset so it falls back to HOME.
if [ -n "${GOTHAM_TERMINAL_HAS_ZDOTDIR-}" ]; then
  ZDOTDIR="${GOTHAM_TERMINAL_USER_ZDOTDIR}"
  export ZDOTDIR
else
  unset ZDOTDIR
fi
if [ -n "${ZDOTDIR-}" ]; then
  __gotham_rc_dir="$ZDOTDIR"
elif [ -n "${HOME-}" ]; then
  __gotham_rc_dir="$HOME"
else
  __gotham_rc_dir=
fi
if [ -n "${__gotham_rc_dir-}" ] && [ -r "${__gotham_rc_dir}/.zshrc" ]; then
  . "${__gotham_rc_dir}/.zshrc"
fi
# The operator's .zshrc may have set, changed or unset ZDOTDIR; that is the
# value a plain zsh would leave behind and what the live session must keep.
if [ -n "${ZDOTDIR-}" ]; then
  export GOTHAM_TERMINAL_USER_ZDOTDIR="$ZDOTDIR"
  export GOTHAM_TERMINAL_HAS_ZDOTDIR=1
else
  unset GOTHAM_TERMINAL_USER_ZDOTDIR
  unset GOTHAM_TERMINAL_HAS_ZDOTDIR
fi

# The probes below must not trip ERR_EXIT (the operator's rc may have set it);
# the operator's choice is restored at the end.
__gotham_saved_errexit=
if [[ -o errexit ]]; then
  __gotham_saved_errexit=1
fi
unsetopt ERR_EXIT 2>/dev/null

# OSC 133 marks: D (previous command finished, with its status) and A (prompt
# starts) before the prompt, B at the end of the prompt where the editable line
# begins, C (preexec) when the line is submitted. The D/A hook is prepended so
# it captures the command's status before a theme's own precmd hooks can
# overwrite $?; the B repair is appended so a theme that rewrites PROMPT keeps
# its prompt and only gains the zero-width mark.
if (( ! ${+functions[__gotham_prompt_start]} )); then
  __gotham_prompt_start() {
    local __gotham_status=$?
    print -n $'\e]133;D;'"$__gotham_status"$'\a\e]133;A\a'
    return $__gotham_status
  }
fi
if (( ! ${+functions[__gotham_prompt_end]} )); then
  __gotham_prompt_end() {
    if [[ ${PROMPT-} != *$'\e]133;B\a'* ]]; then
      PROMPT="${PROMPT-}"$'%{\e]133;B\a%}'
    fi
  }
fi
if (( ! ${+functions[__gotham_preexec]} )); then
  __gotham_preexec() {
    print -n $'\e]133;C\a'
  }
fi
if (( ! ${+functions[__gotham_line_init]} )); then
  __gotham_line_init() {
    print -n $'\e]133;B\a'
  }
fi

if [[ " ${precmd_functions[*]-} " != *" __gotham_prompt_start "* ]]; then
  typeset -ga precmd_functions
  precmd_functions=(__gotham_prompt_start ${precmd_functions[@]-})
fi
if [[ " ${precmd_functions[*]-} " != *" __gotham_prompt_end "* ]]; then
  autoload -Uz add-zsh-hook 2>/dev/null
  add-zsh-hook precmd __gotham_prompt_end 2>/dev/null
fi
if [[ " ${preexec_functions[*]-} " != *" __gotham_preexec "* ]]; then
  autoload -Uz add-zsh-hook 2>/dev/null
  add-zsh-hook preexec __gotham_preexec 2>/dev/null
fi
# zsh < 5.3 has no add-zle-hook-widget: A/B/C/D still work, and the next prompt
# re-adds B, so the missing line-init hook is safe.
if autoload -Uz +X add-zle-hook-widget 2>/dev/null; then
  if [[ " ${zle_line_init_functions[*]-} " != *" __gotham_line_init "* ]]; then
    add-zle-hook-widget line-init __gotham_line_init 2>/dev/null
  fi
fi

if [ -n "$__gotham_saved_errexit" ]; then
  setopt ERR_EXIT
fi

# Restore the ZDOTDIR a plain zsh would leave in the live session (the
# operator's custom value, or unset). The private directory was only needed for
# this startup; children must read the operator's own rc files. The line-init
# widget emits B again after Ctrl-C; a repeated B is a no-op for the web prompt
# scanner, which emits only on a phase change.
if [ -n "${GOTHAM_TERMINAL_HAS_ZDOTDIR-}" ]; then
  export ZDOTDIR="$GOTHAM_TERMINAL_USER_ZDOTDIR"
else
  unset ZDOTDIR
fi
unset GOTHAM_TERMINAL_USER_ZDOTDIR GOTHAM_TERMINAL_HAS_ZDOTDIR GOTHAM_TERMINAL_ZDOTDIR
unset __gotham_saved_errexit __gotham_rc_dir
`

const terminalRcDirPrefix = "gotham-terminal-"

const (
	terminalZshZdotdirVar         = "GOTHAM_TERMINAL_ZDOTDIR"
	terminalZshOriginalZdotdirVar = "GOTHAM_TERMINAL_ORIGINAL_ZDOTDIR"
	terminalZshUserZdotdirVar     = "GOTHAM_TERMINAL_USER_ZDOTDIR"
)

func shellName(path string) string {
	return filepath.Base(strings.TrimSpace(path))
}

func bashShell(path string) bool { return shellName(path) == "bash" }

func zshShell(path string) bool { return shellName(path) == "zsh" }

type terminalShellSetup struct {
	args    []string
	env     []string
	cleanup func()
}

func terminalShellSetupFor(shell string, integration bool) (terminalShellSetup, error) {
	if !integration {
		return terminalShellSetup{}, nil
	}
	switch {
	case bashShell(shell):
		args, cleanup, err := terminalBashRcArgs(shell, true)
		return terminalShellSetup{args: args, cleanup: cleanup}, err
	case zshShell(shell):
		return terminalZshSetup()
	default:
		return terminalShellSetup{}, nil
	}
}

func writeTerminalIntegrationFile(path, content string) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return fmt.Errorf("terminal: create integration rcfile: %w", err)
	}
	if _, err := file.WriteString(content); err != nil {
		_ = file.Close()
		return fmt.Errorf("terminal: write integration rcfile: %w", err)
	}
	if err := file.Close(); err != nil {
		return fmt.Errorf("terminal: write integration rcfile: %w", err)
	}
	return nil
}

func terminalBashRcArgs(shell string, integration bool) ([]string, func(), error) {
	if !integration || !bashShell(shell) {
		return nil, nil, nil
	}
	dir, err := os.MkdirTemp("", terminalRcDirPrefix)
	if err != nil {
		return nil, nil, fmt.Errorf("terminal: create integration directory: %w", err)
	}
	cleanup := func() { _ = os.RemoveAll(dir) }
	path := filepath.Join(dir, "bashrc")
	if err := writeTerminalIntegrationFile(path, docker.BashIntegrationScript); err != nil {
		cleanup()
		return nil, nil, err
	}
	return []string{"--rcfile", path}, cleanup, nil
}

func terminalZshSetup() (terminalShellSetup, error) {
	dir, err := os.MkdirTemp("", terminalRcDirPrefix)
	if err != nil {
		return terminalShellSetup{}, fmt.Errorf("terminal: create integration directory: %w", err)
	}
	cleanup := func() { _ = os.RemoveAll(dir) }
	for _, file := range []struct {
		name    string
		content string
	}{
		{name: ".zshenv", content: terminalZshEnvScript},
		{name: ".zshrc", content: terminalZshRcScript},
	} {
		if err := writeTerminalIntegrationFile(filepath.Join(dir, file.name), file.content); err != nil {
			cleanup()
			return terminalShellSetup{}, err
		}
	}
	original := strings.TrimSpace(os.Getenv("ZDOTDIR"))
	if !filepath.IsAbs(original) {
		original = ""
	}
	return terminalShellSetup{
		env: []string{
			"ZDOTDIR=" + dir,
			terminalZshZdotdirVar + "=" + dir,
			terminalZshOriginalZdotdirVar + "=" + original,
		},
		cleanup: cleanup,
	}, nil
}
