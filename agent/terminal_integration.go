package agent

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// This file holds the optional bash startup integration (JUS-263): a constant
// rcfile that keeps the operator's own startup files, adds colour defaults and
// emits the OSC 133 prompt marks that quick-command suggestions need. The text
// below is a constant of the agent.
// It is never built from request data (cwd, root, service, container, env), so
// a browser cannot influence what the shell executes.

// terminalBashIntegrationScript is sourced by every interactive bash session
// (host: --rcfile; container: --rcfile on a here-document fd). It is additive
// and idempotent: the operator's ~/.bashrc runs first, and a prompt, alias or
// PROMPT_COMMAND the operator set is never overwritten. Bash itself runs the
// system-wide startup file (/etc/bash.bashrc on Debian/Ubuntu) before --rcfile,
// so this file only adds the personal file, then the Gotham defaults.
//
// Compatibility: bash 3.2+ (no `\e` prompt escape; PS0/C only where bash
// supports it), `set -u` and `set -e` user rcs, PROMPT_COMMAND as a string or
// an array, and a HOME that is unset or does not contain .bashrc. It never reads
// the shell's stdin.
const terminalBashIntegrationScript = `# Gotham terminal integration (generated by the node agent; do not edit).
# Additive and optional: the operator's ~/.bashrc is sourced first and wins.
# This file only fills in what the operator did not customise, then adds the
# OSC 133 prompt marks. It never reads stdin and is safe to source twice.

case "${__gotham_integration_loaded-}" in
  1) return 0 ;;
esac
__gotham_integration_loaded=1

# The probes below must not trip set -e. Disable it before sourcing the
# operator's rc and again after (the rc may enable it); an errexit that was on
# before or after the rc is restored at the end.
__gotham_saved_errexit=
case $- in
  *e*) __gotham_saved_errexit=1 ;;
esac
set +e
__gotham_ps1_before=${PS1-}
if [ -n "${HOME-}" ] && [ -r "$HOME/.bashrc" ]; then
  . "$HOME/.bashrc"
fi
set +e
case $- in
  *e*) __gotham_saved_errexit=1 ;;
esac

# A coloured user@host + cwd prompt, only when the operator's rc left the
# inherited prompt untouched. A custom PS1 (or theme) always wins.
if [ "${PS1-}" = "$__gotham_ps1_before" ]; then
  PS1='\[\033[01;32m\]\u@\h\[\033[00m\]:\[\033[01;34m\]\w\[\033[00m\]\$ '
fi

# Colour defaults for common commands, only where the operator has not already
# aliased or wrapped the command. Each probe accepts the flag only when the
# installed tool understands it (GNU vs BSD), so no broken alias is installed.
if ! alias ls >/dev/null 2>&1 && ! declare -F ls >/dev/null 2>&1; then
  command ls --color=auto -d / >/dev/null 2>&1 && alias ls='ls --color=auto'
fi
if ! alias grep >/dev/null 2>&1 && ! declare -F grep >/dev/null 2>&1; then
  printf '' | command grep --color=auto gotham-probe >/dev/null 2>&1
  [ $? -lt 2 ] && alias grep='grep --color=auto'
fi
if ! alias diff >/dev/null 2>&1 && ! declare -F diff >/dev/null 2>&1; then
  command diff --color=auto /dev/null /dev/null >/dev/null 2>&1 && alias diff='diff --color=auto'
fi
if ! alias ip >/dev/null 2>&1 && ! declare -F ip >/dev/null 2>&1; then
  command -v ip >/dev/null 2>&1 && command ip -color=auto address >/dev/null 2>&1 && alias ip='ip -color=auto'
fi

# OSC 133 marks: D (previous command finished, with its status) and A (prompt
# starts) immediately before the prompt, B at the end of the prompt where the
# editable line begins, C (PS0, bash >= 4.4) when the line is submitted.
if ! declare -F __gotham_prompt_command >/dev/null 2>&1; then
  __gotham_prompt_command() {
    local __gotham_status=$?
    printf '\033]133;D;%s\a' "$__gotham_status"
    printf '\033]133;A\a'
    case ${PS1-} in
      *'133;B'*) ;;
      *) PS1=${PS1-}'\[\033]133;B\a\]' ;;
    esac
    return "$__gotham_status"
  }
fi
# Themes replace PS1 from their own PROMPT_COMMAND entry, which runs after the
# first function above. This repair runs last and re-adds only the B mark, so a
# custom prompt is kept byte for byte apart from the zero-width mark.
if ! declare -F __gotham_prompt_command_end >/dev/null 2>&1; then
  __gotham_prompt_command_end() {
    case ${PS1-} in
      ''|*'133;B'*) ;;
      *) PS1=${PS1}'\[\033]133;B\a\]' ;;
    esac
  }
fi
__gotham_pc_kind=$(declare -p PROMPT_COMMAND 2>/dev/null) || __gotham_pc_kind=
case "$__gotham_pc_kind" in
  'declare -a'*|'declare -A'*)
    case " ${PROMPT_COMMAND[*]-} " in
      *__gotham_prompt_command_end*) ;;
      *)
        if [ "${#PROMPT_COMMAND[@]}" -gt 0 ]; then
          PROMPT_COMMAND=(__gotham_prompt_command "${PROMPT_COMMAND[@]}" __gotham_prompt_command_end)
        else
          PROMPT_COMMAND=(__gotham_prompt_command __gotham_prompt_command_end)
        fi
        ;;
    esac
    ;;
  *)
    case "${PROMPT_COMMAND-}" in
      *__gotham_prompt_command_end*) ;;
      *)
        __gotham_pc=${PROMPT_COMMAND-}
        while [ "${__gotham_pc%;}" != "$__gotham_pc" ]; do
          __gotham_pc=${__gotham_pc%;}
        done
        PROMPT_COMMAND="__gotham_prompt_command${__gotham_pc:+; $__gotham_pc}; __gotham_prompt_command_end"
        ;;
    esac
    ;;
esac
case "${PS0-}" in
  *'133;C'*) ;;
  *) PS0='\[\033]133;C\a\]'"${PS0-}" ;;
esac

if [ -n "$__gotham_saved_errexit" ]; then set -e; fi
unset __gotham_saved_errexit __gotham_ps1_before __gotham_pc_kind __gotham_pc
`

// containerBashRcPrelude/Epilogue wrap the constant integration script in the
// command that starts the probed bash as the interactive shell. The quoted
// here-document keeps the script out of the container's filesystem and is not
// subject to expansion; fd 3 survives the exec. When the container has no
// /dev/fd, plain interactive bash is the fallback. The whole command text is a
// constant of the agent: no request data is interpolated into it.
const containerBashRcPrelude = `if [ -d /dev/fd ]; then
exec "$0" --rcfile /dev/fd/3 -i 3<<'GOTHAM_RC_EOF'
`
const containerBashRcEpilogue = `
GOTHAM_RC_EOF
fi
exec "$0" -i`

// containerBashRcCommand returns the exact command text a container bash is
// started with.
func containerBashRcCommand() string {
	return containerBashRcPrelude + terminalBashIntegrationScript + containerBashRcEpilogue
}

// bashShell reports whether path names the bash shell. The integration is
// bash-only; zsh, sh/dash, ash and an operator-configured shell are never given
// bash startup arguments.
func bashShell(path string) bool {
	return filepath.Base(strings.TrimSpace(path)) == "bash"
}

// terminalBashRcArgs returns the extra arguments for a host bash session and a
// cleanup that removes the private rcfile. The rcfile lives in a fresh 0700
// directory, is 0600, and is removed when the session ends. A non-bash shell or
// a disabled integration returns no arguments and no cleanup.
func terminalBashRcArgs(shell string, integration bool) ([]string, func(), error) {
	if !integration || !bashShell(shell) {
		return nil, nil, nil
	}
	dir, err := os.MkdirTemp("", "gotham-terminal-")
	if err != nil {
		return nil, nil, fmt.Errorf("terminal: create integration directory: %w", err)
	}
	cleanup := func() { _ = os.RemoveAll(dir) }
	path := filepath.Join(dir, "bashrc")
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		cleanup()
		return nil, nil, fmt.Errorf("terminal: create integration rcfile: %w", err)
	}
	if _, err := file.WriteString(terminalBashIntegrationScript); err != nil {
		_ = file.Close()
		cleanup()
		return nil, nil, fmt.Errorf("terminal: write integration rcfile: %w", err)
	}
	if err := file.Close(); err != nil {
		cleanup()
		return nil, nil, fmt.Errorf("terminal: write integration rcfile: %w", err)
	}
	return []string{"--rcfile", path}, cleanup, nil
}

// containerBashCommand wraps command (the probed or requested shell) with the
// constant integration script when it is bash and the integration is enabled.
// Images without bash (sh/ash/other) keep their exact current command.
func containerBashCommand(command []string, integration bool) []string {
	if !integration || len(command) != 1 || !bashShell(command[0]) {
		return command
	}
	shell := command[0]
	return []string{shell, "-c", containerBashRcCommand()}
}
