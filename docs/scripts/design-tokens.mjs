#!/usr/bin/env node
// Generates and checks docs/public/design-system from the authoritative runtime tokens.
// Effective :root declarations, last duplicate wins; values are copied verbatim with
// whitespace normalized (color-mix aliases and font stacks stay exact).
// Usage (from docs/): node scripts/design-tokens.mjs --write | --check
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const docsDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(docsDir, "public/design-system");
const runtimeFile = resolve(docsDir, "../web/src/shared/styles/tokens.css");
const previewFile = join(outDir, "design-preview.html");
const styleBlock = /(<style id="gotham-tokens">)[\s\S]*?(<\/style>)/;
const dataBlock =
  /(<script type="application\/json" id="gotham-token-data">)[\s\S]*?(<\/script>)/;

const CATEGORIES = [
  "color",
  "typography",
  "spacing",
  "layout",
  "radius",
  "elevation",
  "motion",
  "brand",
  "editor",
  "terminal",
];
const RULES = [
  [/^--term-/, "terminal"],
  [/^--editor-/, "editor"],
  [/^--brand-/, "brand"],
  [/^--(font|text|leading|tracking)-/, "typography"],
  [/^--(space|section-y|form-item-gap)/, "spacing"],
  [/^--radius-/, "radius"],
  [/^--(elev|focus-ring)/, "elevation"],
  [/^--(motion|ease)-/, "motion"],
  [/^--(rail|sidebar|context|topbar|container|modal-width)/, "layout"],
];
const COLORS = new Set(
  "bg surface surface-warm fg fg-2 muted meta border border-soft accent accent-on accent-hover accent-active success warn danger fg-soft hover-row selected-row accent-soft accent-softer accent-ink accent-ink-hover link success-soft warn-soft danger-soft success-ink warn-ink danger-ink float"
    .split(" ")
    .map((name) => `--${name}`),
);

function parseRoot(css) {
  // shortcut: reads flat :root blocks; use a CSS parser if token values gain semicolons or nested rules.
  const tokens = new Map();
  for (const block of css.matchAll(/:root\s*\{([^}]*)\}/g)) {
    for (const [, name, value] of block[1].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) {
      tokens.set(name, value.replace(/\s+/g, " ").trim());
    }
  }
  return tokens;
}

function build(tokens) {
  const categories = Object.fromEntries(CATEGORIES.map((name) => [name, []]));
  for (const name of tokens.keys()) {
    const category =
      RULES.find(([pattern]) => pattern.test(name))?.[1] ?? (COLORS.has(name) ? "color" : null);
    assert.ok(category, `unclassified token ${name}: add a rule or colour entry in scripts/design-tokens.mjs`);
    categories[category].push(name);
  }
  return {
    name: "gotham-design-tokens",
    version: 1,
    generatedFrom: "web/src/shared/styles/tokens.css",
    generatedBy: "docs/scripts/design-tokens.mjs --write",
    note:
      "Effective :root declarations from tokens.css (later duplicates win). " +
      "Values are whitespace-normalized but otherwise verbatim, including color-mix() aliases. " +
      "No @font-face or remote URLs: font stacks fall back to system fonts offline.",
    count: tokens.size,
    categories,
    tokens: Object.fromEntries(tokens),
  };
}

const rootBlock = (tokens) =>
  `:root {\n${[...tokens].map(([name, value]) => `  ${name}: ${value};`).join("\n")}\n}`;

const previewData = (block) =>
  JSON.parse(block.replace(/^<script[^>]*>/, "").replace(/<\/script>$/, ""));

function renderPreview(preview, tokens, data) {
  assert.match(preview, styleBlock, "design-preview.html needs the #gotham-tokens style block");
  assert.match(preview, dataBlock, "design-preview.html needs the #gotham-token-data JSON block");
  const json = JSON.stringify(data, null, 2);
  return preview
    .replace(styleBlock, (_match, open, close) => `${open}\n${rootBlock(tokens)}\n${close}`)
    .replace(dataBlock, (_match, open, close) => `${open}${json}${close}`);
}

function main(write) {
  // Fixture: the second :root wins and a color-mix alias is copied verbatim.
  const fixture =
    ":root { --a: 1px; --m: color-mix(in oklab, var(--a), black 14%); } :root { --a: 40px; }";
  assert.deepEqual([...parseRoot(fixture)], [
    ["--a", "40px"],
    ["--m", "color-mix(in oklab, var(--a), black 14%)"],
  ]);

  const tokens = parseRoot(readFileSync(runtimeFile, "utf8"));
  assert.ok(tokens.size > 0, "tokens.css has no :root declarations");
  const data = build(tokens);
  const json = `${JSON.stringify(data, null, 2)}\n`;
  const css = `/* Gotham design tokens (effective :root values).\n * Generated from web/src/shared/styles/tokens.css by docs/scripts/design-tokens.mjs --write.\n * tokens.css is authoritative; do not edit this file by hand.\n */\n${rootBlock(tokens)}\n`;
  const preview = readFileSync(previewFile, "utf8");
  const next = renderPreview(preview, tokens, data);

  if (write) {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(join(outDir, "design-tokens.json"), json);
    writeFileSync(join(outDir, "design-tokens.css"), css);
    writeFileSync(previewFile, next);
    console.log(`design tokens: wrote JSON, CSS and preview blocks (${tokens.size} tokens)`);
    return;
  }

  assert.deepEqual(JSON.parse(readFileSync(join(outDir, "design-tokens.json"), "utf8")), data);
  assert.equal(readFileSync(join(outDir, "design-tokens.css"), "utf8"), css, "design-tokens.css is stale");
  assert.doesNotMatch(css, /@font-face\s*\{|@import/, "design-tokens.css must not load fonts or imports");
  assert.equal(preview, next, "design-preview.html token blocks are stale");
  assert.doesNotMatch(preview, /@import|@font-face\s*\{/, "design-preview.html must be self-contained");
  assert.doesNotMatch(
    preview,
    /<(?:link|script|img)\b[^>]*(?:src|href)=["']https?:/i,
    "design-preview.html loads a remote resource",
  );
  assert.deepEqual([...parseRoot(preview.match(styleBlock)[0])], [...tokens]);
  assert.deepEqual(previewData(preview.match(dataBlock)[0]), data);
  const script = preview.match(/<script(?![^>]*type=)[^>]*>([\s\S]*?)<\/script>/)[1];
  assert.doesNotThrow(() => new Function(script), "design-preview.html inline script does not compile");

  console.log(`design tokens: ok — ${tokens.size} effective tokens match JSON, CSS and preview`);
}

const mode = process.argv[2];
assert.ok(mode === "--write" || mode === "--check", "usage: node scripts/design-tokens.mjs --write | --check");
main(mode === "--write");
